#!/usr/bin/env python3
"""engineassets/staring.jpg -> blank/src/blankimg.h (+ blank/ICON0.PNG): the picture of the Blank Engine.

The image is scaled to cover the 480x272 screen (cropped to fit), reduced to one 256-colour palette and stored as
an 8-bit indexed (T8) texture whose rows are 512 texels wide, the power-of-two stride the GE needs. Only the 272
visible rows are stored; the texture is declared 512x512 and the unused rows are never sampled.
Usage: mkblankimg.py [IMAGE]"""
import sys
from pathlib import Path
from PIL import Image
root = Path(__file__).resolve().parents[1]
src = Path(sys.argv[1]) if len(sys.argv) > 1 else root / 'engineassets/staring.jpg'
im = Image.open(src).convert('RGB')
# cover 480x272: scale so both sides are at least the screen, then crop the centre
k = max(480 / im.width, 272 / im.height)
im = im.resize((round(im.width * k), round(im.height * k)), Image.Resampling.LANCZOS)
x0, y0 = (im.width - 480) // 2, (im.height - 272) // 2
im = im.crop((x0, y0, x0 + 480, y0 + 272))
q = im.quantize(256, method=Image.Quantize.MEDIANCUT, dither=Image.Dither.FLOYDSTEINBERG)
pal = q.getpalette()[:768] + [0] * (768 - len(q.getpalette()[:768]))
clut = [0xFF000000 | (pal[i * 3 + 2] << 16) | (pal[i * 3 + 1] << 8) | pal[i * 3] for i in range(256)]   # 0xAABBGGRR
px = q.tobytes()
rows = b''.join(px[y * 480:(y + 1) * 480] + bytes(32) for y in range(272))   # pad each row to 512
out = ['/* generated by tools/mkblankimg.py from %s - do not edit */' % src.name,
       'static const unsigned int __attribute__((aligned(16))) blank_clut[256] = {']
for i in range(0, 256, 8):
    out.append('    ' + ', '.join('0x%08x' % v for v in clut[i:i + 8]) + ',')
out += ['};', 'static const unsigned char __attribute__((aligned(16))) blank_img[512 * 272] = {']
for i in range(0, len(rows), 64):
    out.append(','.join(str(b) for b in rows[i:i + 64]) + ',')
out.append('};')
(root / 'blank/src/blankimg.h').write_text('\n'.join(out) + '\n')
# XMB icon: 144x80 from the same picture
icon = Image.open(src).convert('RGB')
k = max(144 / icon.width, 80 / icon.height)
icon = icon.resize((round(icon.width * k), round(icon.height * k)), Image.Resampling.LANCZOS)
x0, y0 = (icon.width - 144) // 2, (icon.height - 80) // 2
icon.crop((x0, y0, x0 + 144, y0 + 80)).save(root / 'blank/ICON0.PNG')
print('blankimg.h: 480x272 T8, %d KB; ICON0.PNG 144x80' % (len(rows) // 1024))
