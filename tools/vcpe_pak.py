"""VCPE PAK writer for converters: one data file with the header vcpe_pak_open_checked() reads
{char magic[4]; u32 total size; u32 build stamp} padded to 64 bytes, then 64-byte aligned sections, plus the C
header the EBOOT is built with (PAK_SIZE, PAK_STAMP, PAK_<NAME>_OFF/_SIZE), so an EBOOT and a PAK from different
builds refuse each other with a readable message instead of reading garbage.

    from vcpe_pak import write_pak
    offs = write_pak('build/GAME.PAK', 'build/gen/pakinfo.h', [('sprites', spr_bytes), ('rooms', room_bytes)])
"""
import struct
import time


def align(b, n=64):
    return b + b'\0' * (-len(b) % n)


def write_pak(pak_path, header_path, sections, magic=b'GPAK', stamp=None, prefix='PAK'):
    """sections: [(name, bytes)]; returns {name: (offset, size)}"""
    stamp = (int(time.time()) & 0x7fffffff) if stamp is None else stamp
    body = bytearray()
    offs = {}
    for name, data in sections:
        body += b'\0' * (-len(body) % 64)
        offs[name] = (64 + len(body), len(data))
        body += data
    total = 64 + len(align(bytes(body)))
    with open(pak_path, 'wb') as f:
        f.write(struct.pack('<4sII', magic, total, stamp).ljust(64, b'\0'))
        f.write(align(bytes(body)))
    if header_path:
        guard = prefix + '_INFO_H'
        h = ['/* generated by vcpe_pak.py - do not edit */', '#ifndef ' + guard, '#define ' + guard,
             '#define %s_MAGIC "%s"' % (prefix, magic.decode('ascii')),
             '#define %s_SIZE %du' % (prefix, total), '#define %s_STAMP %du' % (prefix, stamp)]
        for name, (o, n) in offs.items():
            h += ['#define %s_%s_OFF %du' % (prefix, name.upper(), o), '#define %s_%s_SIZE %du' % (prefix, name.upper(), n)]
        h += ['#endif', '']
        with open(header_path, 'w') as f:
            f.write('\n'.join(h))
    return offs
